import { expect, test } from '@playwright/test'

test('a celestial input keeps body edits, scrollers, steps and native submission synchronized', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('./?input')
  const field = page.getByRole('button', { name: 'Appointment', exact: true })
  await expect(field).toHaveCSS('height', '32px')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await field.click()
  const panel = page.getByRole('dialog', { name: 'Appointment', exact: true })
  await expect(panel.getByRole('listbox')).toHaveCount(3)
  await expect(panel.getByRole('button', { name: 'Increase day', exact: true })).toBeVisible()
  await expect(panel.getByRole('radio')).toHaveCount(0)
  await expect(panel.locator('[data-visible-bodies]')).toHaveAttribute('data-visible-bodies', 'earth jupiter')
  await panel.getByRole('listbox', { name: 'Year', exact: true }).press('ArrowDown')
  await expect(panel.getByRole('listbox', { name: 'Year', exact: true }).getByRole('option', { selected: true })).toHaveText('2029')
  await panel.getByRole('slider', { name: 'Day of year on the calendar ring', exact: true }).press('ArrowRight')
  await panel.getByRole('button', { name: 'Increase day', exact: true }).click()
  await expect(panel.getByRole('listbox', { name: 'Month', exact: true }).getByRole('option', { selected: true })).toHaveText('Feb')
  await panel.getByRole('listbox', { name: 'Month', exact: true }).press('ArrowDown')
  await expect(panel.getByRole('slider', { name: 'Day of year on the calendar ring', exact: true })).toHaveAttribute('aria-valuenow', '61')
  await panel.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(field).toBeFocused()
  await expect(field).toContainText('2029-03-02')
  await page.getByRole('button', { name: 'Submit appointment', exact: true }).click()
  await expect(page.getByTestId('input-result')).toContainText('"when":"2029-03-02"')
})

test('Earth time and exact steps share precision, follow system theme and respect read-only values', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce', colorScheme: 'light' })
  await page.goto('./?input&timeonly&system')
  const field = page.getByRole('button', { name: 'Appointment', exact: true })
  await field.click()
  let panel = page.getByRole('dialog', { name: 'Appointment', exact: true })
  await expect(panel).toHaveCSS('background-color', 'rgb(255, 255, 255)')
  await expect(panel).not.toContainText(/One swipe|TIME ON EARTH|A MOMENT IN ORBIT|Drag/)
  await expect(panel.locator('.picker-form-panel-title')).toHaveCount(0)
  await expect(panel.locator('[data-scene-theme]')).toHaveAttribute('data-scene-theme', 'light')
  await panel.getByRole('button', { name: 'Increase minutes', exact: true }).click()
  await expect(panel.getByRole('listbox', { name: 'Hours', exact: true }).getByRole('option', { selected: true })).toHaveText('00')
  await expect(panel.getByRole('listbox', { name: 'Minutes', exact: true }).getByRole('option', { selected: true })).toHaveText('14')
  await expect(page.getByTestId('input-date')).toHaveText('2028-01-31T16:14:00.000Z')
  await panel.getByRole('slider', { name: 'Rotate Earth to set time', exact: true }).press('ArrowRight')
  await expect(panel.getByRole('listbox', { name: 'Minutes', exact: true }).getByRole('option', { selected: true })).toHaveText('29')
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(panel).toHaveCSS('background-color', 'rgb(11, 17, 27)')
  await expect(panel.locator('[data-scene-theme]')).toHaveAttribute('data-scene-theme', 'dark')
  await panel.press('Escape')
  await page.goto('./?input&readonly')
  await field.click()
  panel = page.getByRole('dialog', { name: 'Appointment', exact: true })
  await expect(panel.getByRole('listbox', { name: 'Day', exact: true })).toHaveAttribute('aria-disabled', 'true')
  await expect(panel.getByRole('button', { name: 'Increase day', exact: true })).toBeDisabled()
  await expect(panel.getByRole('slider', { name: 'Day of year on the calendar ring', exact: true })).toHaveAttribute('aria-disabled', 'true')
})

test('year-only and decorative celestial inputs keep their configured controls on narrow screens', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 740 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('./?input&year')
  const field = page.getByRole('button', { name: 'Appointment', exact: true })
  await field.click()
  let panel = page.getByRole('dialog', { name: 'Appointment', exact: true })
  await expect(panel.getByRole('listbox')).toHaveCount(1)
  await panel.getByRole('slider', { name: 'Year on Jupiter’s orbit', exact: true }).press('ArrowRight')
  await expect(panel.getByRole('listbox', { name: 'Year', exact: true }).getByRole('option', { selected: true })).toHaveText('2033')
  const box = (await panel.boundingBox())!
  expect(box.x).toBeGreaterThanOrEqual(0)
  expect(box.x + box.width).toBeLessThanOrEqual(320)
  expect(await panel.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
  const done = (await panel.getByRole('button', { name: 'Done', exact: true }).boundingBox())!
  expect(done.y + done.height).toBeLessThanOrEqual(740)
  await panel.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(field).toContainText('2033')
  await page.goto('./?input&moon')
  await field.click()
  panel = page.getByRole('dialog', { name: 'Appointment', exact: true })
  await expect(panel.locator('[data-scene]')).toHaveAttribute('data-scene', 'moon')
  await expect(panel.getByRole('listbox')).toHaveCount(3)
  await expect(panel.getByRole('button', { name: 'Increase day', exact: true })).toBeVisible()
  await expect(panel.getByRole('slider')).toHaveCount(0)
})


test('combined orbital and Earth edits support custom parts and keep popovers attached to the field', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('./?input&combined&custom')
  const field = page.getByRole('button', { name: 'Appointment', exact: true })
  await expect(field).toHaveClass(/appointment-field/)
  await expect(field).toHaveCSS('border-radius', '18px')
  await field.click()
  const panel = page.getByRole('dialog', { name: 'Appointment', exact: true })
  await expect(panel).toHaveCSS('background-color', 'rgb(250, 245, 255)')
  await expect(panel.locator('[data-visible-bodies]')).toHaveAttribute('data-visible-bodies', 'earth jupiter')
  await expect(panel.locator('.appointment-earth')).toBeVisible()
  await expect(panel.getByRole('listbox', { name: 'Day', exact: true })).toHaveCSS('height', '240px')
  const selected = panel.getByRole('listbox', { name: 'Day', exact: true }).getByRole('option', { selected: true })
  await expect(selected).toHaveCSS('color', 'rgb(124, 58, 237)')
  await panel.getByRole('listbox', { name: 'Day', exact: true }).press('ArrowUp')
  await expect(selected).toHaveText('30')
  await panel.getByRole('slider', { name: 'Year on Jupiter’s orbit', exact: true }).press('ArrowRight')
  await expect(panel.getByRole('listbox', { name: 'Year', exact: true }).getByRole('option', { selected: true })).toHaveText('2029')
  await panel.getByRole('slider', { name: 'Rotate Earth to set time', exact: true }).press('ArrowRight')
  await expect(page.getByTestId('input-date')).toHaveText('2029-01-30T16:14:00.000Z')
  const anchor = (await field.boundingBox())!
  const box = (await panel.boundingBox())!
  expect(box.y).toBeGreaterThanOrEqual(anchor.y + anchor.height + 5)
  expect(box.x).toBe(anchor.x)
  // Wheel geometry, value mapping and selection stay aligned after custom sizing.
  await expect(panel.getByRole('listbox', { name: 'Minutes', exact: true }).getByRole('option', { selected: true })).toHaveText('14')
  await panel.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(field).toContainText('2029-01-31 · 00:14')
})
