import { expect, test } from '@playwright/test'

for (const variant of ['celestial', 'lcd']) test(`${variant} second drags, wheel selection and year-only scenes remain synchronized`, async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto(`./?input&timeonly&seconds${variant === 'lcd' ? '&lcd' : ''}`)
  await page.getByRole('button', { name: 'Appointment', exact: true }).click()
  const panel = page.getByRole('dialog', { name: 'Appointment', exact: true })
  const tabs = panel.getByRole('group', { name: 'Earth drag precision' })
  await expect.poll(() => panel.getByRole('listbox', { name: 'Hours', exact: true }).evaluate((wheel) => Math.abs(wheel.querySelector('[aria-selected="true"]')!.getBoundingClientRect().top - wheel.parentElement!.querySelector('.picker-wheel-selection')!.getBoundingClientRect().top))).toBeLessThan(1)
  await expect(tabs.getByRole('button')).toHaveCount(3)
  await tabs.getByRole('button', { name: 'Seconds', exact: true }).click()
  const globe = panel.getByRole('slider', { name: 'Rotate Earth to set time', exact: true })
  const box = (await globe.boundingBox())!
  await page.mouse.move(box.x + box.width * .25, box.y + box.height * .5)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width * .5, box.y + box.height * .5, { steps: 24 })
  await page.mouse.up()
  const seconds = panel.getByRole('listbox', { name: 'Seconds', exact: true })
  await expect(seconds.getByRole('option', { selected: true })).toHaveText('15')
  await expect.poll(() => seconds.evaluate((el) => {
    const selected = el.querySelector('[aria-selected="true"]')!.getBoundingClientRect()
    const band = el.parentElement!.querySelector('.picker-wheel-selection')!.getBoundingClientRect()
    return Math.abs(selected.top - band.top)
  })).toBeLessThan(1)
  await seconds.press('ArrowDown')
  await globe.press('ArrowRight')
  await expect(page.getByTestId('input-date')).toHaveText('2028-01-31T15:59:17.000Z')
  await page.goto(`./?input&year${variant === 'lcd' ? '&lcd' : ''}`)
  await page.getByRole('button', { name: 'Appointment', exact: true }).click()
  await expect(panel.locator('[data-visible-bodies]')).toHaveAttribute('data-visible-bodies', 'jupiter')
  await expect(panel.locator('[data-picker-part="dateBadge"], [data-picker-part="monthLabel"]')).toHaveCount(0)
  await expect(panel.getByRole('slider')).toHaveCount(1)
  await panel.getByRole('slider', { name: 'Year on Jupiter’s orbit', exact: true }).press('ArrowRight')
  await expect(page.getByTestId('input-date')).toHaveText('2033-01-31T15:59:00.000Z')
})
