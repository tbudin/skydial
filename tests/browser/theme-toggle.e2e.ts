import AxeBuilder from '@axe-core/playwright'
import { expect, test } from '@playwright/test'

for (const variant of ['celestial', 'lcd']) test(`${variant} binary toggle works standalone, controlled and with a shared theme`, async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'light', reducedMotion: 'no-preference' })
  await page.goto(`?theme&controlled${variant === 'lcd' ? '&lcd' : ''}`)
  const toggle = page.getByRole('switch', { name: 'Page appearance', exact: true })
  await expect(toggle).toHaveAttribute('aria-checked', 'false')
  const selection = toggle.locator('[data-theme-toggle-part="selection"]')
  const start = await selection.boundingBox()
  await toggle.focus()
  await page.keyboard.press('Space')
  await expect(toggle).toHaveAttribute('aria-checked', 'true')
  await expect(page.getByTestId('theme-state')).toHaveText('dark/dark')
  await expect(selection).toHaveCSS('transition-duration', '0.2s')
  await expect.poll(async () => (await selection.boundingBox())!.x).toBeGreaterThan(start!.x + 20)
  await expect(toggle.locator('[data-theme-toggle-part="sun"]')).toHaveCSS('opacity', '0')
  await expect(toggle.locator('[data-theme-toggle-part="moon"]')).toHaveCSS('opacity', '1')
  await expect(toggle.locator('..').locator('[data-theme-toggle-part="status"]')).toHaveText('Dark')
  await page.keyboard.press('Enter')
  await expect(toggle).toHaveAttribute('aria-checked', 'false')
  // One switch: every activation toggles, including a click on the active thumb.
  await toggle.locator('[data-theme-toggle-part="selection"]').click()
  await expect(toggle).toHaveAttribute('aria-checked', 'true')
  await toggle.locator('[data-theme-toggle-part="selection"]').click()
  await expect(toggle).toHaveAttribute('aria-checked', 'false')
  await toggle.focus()
  await page.keyboard.press('ArrowRight')
  await expect(toggle).toHaveAttribute('aria-checked', 'true')
  await page.keyboard.press('ArrowLeft')
  await expect(toggle).toHaveAttribute('aria-checked', 'false')
  await toggle.evaluate((element) => { element.dir = 'rtl' })
  await page.keyboard.press('ArrowLeft')
  await expect(toggle).toHaveAttribute('aria-checked', 'true')
  await page.keyboard.press('ArrowRight')
  await expect(toggle).toHaveAttribute('aria-checked', 'false')
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-checked', 'true')
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-checked', 'false')
  const independent = page.getByRole('switch', { name: 'Independent toggle', exact: true })
  await independent.click()
  await expect(independent).toHaveAttribute('aria-checked', 'true')
  await expect(page.getByTestId('theme-state')).toHaveText('light/light')
  await page.getByRole('switch', { name: 'Controlled toggle', exact: true }).click()
  await expect(page.getByTestId('controlled-theme')).toHaveText('dark')
  await expect(page.getByRole('switch', { name: 'Disabled toggle', exact: true })).toBeDisabled()
  if (variant === 'lcd') await expect(toggle.locator('canvas')).toHaveCount(0)
  const audit = await new AxeBuilder({ page }).include('.celestial-theme-toggle').withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()
  expect(audit.violations).toEqual([])
})

for (const variant of ['celestial', 'lcd']) test(`${variant} padded theme menu supports keyboard selection, dismissal and System`, async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'light' })
  await page.goto(`?theme&controlled${variant === 'lcd' ? '&lcd' : ''}`)
  const toggle = page.getByRole('switch', { name: 'Page appearance', exact: true })
  const control = toggle.locator('..')
  const preference = control.getByRole('button', { name: 'Theme preference', exact: true })
  const menu = control.getByRole('menu', { name: 'Theme preference', exact: true })
  await toggle.click()
  await preference.focus()
  await page.keyboard.press('Enter')
  await expect(menu.getByRole('menuitemradio', { name: 'Dark', exact: true })).toBeFocused()
  await expect(menu.getByRole('menuitemradio', { name: 'Dark', exact: true })).toHaveAttribute('aria-checked', 'true')
  for (const item of await menu.getByRole('menuitemradio').all()) {
    expect((await item.boundingBox())!.height).toBeGreaterThanOrEqual(44)
    await expect(item).toHaveCSS('padding-inline-start', '12px')
    await expect(item).toHaveCSS('padding-block-start', '10px')
  }
  await page.keyboard.press('ArrowDown')
  await expect(menu.getByRole('menuitemradio', { name: 'System', exact: true })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(menu).not.toBeVisible()
  await expect(preference).toBeFocused()
  await expect(control.locator('[data-theme-toggle-part="status"]')).toHaveText('System')
  await expect(page.getByTestId('theme-state')).toHaveText('auto/light')
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(toggle).toHaveAttribute('aria-checked', 'true')
  await expect(control).toHaveAttribute('data-theme-preference', 'auto')
  await expect(page.getByTestId('theme-state')).toHaveText('auto/dark')
  await preference.click()
  await page.keyboard.press('Home')
  await expect(menu.getByRole('menuitemradio', { name: 'Light', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(preference).toBeFocused()
  await expect(control).toHaveAttribute('data-theme-preference', 'auto')
  await page.keyboard.press('ArrowDown')
  await expect(menu.getByRole('menuitemradio', { name: 'Light', exact: true })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(control).toHaveAttribute('data-theme-preference', 'light')
  await preference.click()
  await page.keyboard.press('s')
  await expect(menu.getByRole('menuitemradio', { name: 'System', exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(menu).not.toBeVisible()
  await expect(page.getByRole('textbox', { name: 'After theme toggle', exact: true })).toBeFocused()
  await preference.click()
  await page.getByRole('heading', { name: 'One appearance, everywhere' }).click()
  await expect(menu).not.toBeVisible()
  await preference.click()
  await menu.getByRole('menuitemradio', { name: 'Dark', exact: true }).click()
  await expect(control).toHaveAttribute('data-theme-preference', 'dark')
  await preference.click()
  await menu.getByRole('menuitemradio', { name: 'System', exact: true }).click()
  await expect(control).toHaveAttribute('data-theme-preference', 'auto')
  await preference.click()
  const audit = await new AxeBuilder({ page }).include('.celestial-theme-toggle').withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()
  expect(audit.violations).toEqual([])
})

for (const variant of ['celestial', 'lcd']) test(`${variant} menu can be omitted and keyboard focus follows the visible track`, async ({ page }) => {
  await page.goto(`?theme&noMenu${variant === 'lcd' ? '&lcd' : ''}`)
  const toggle = page.getByRole('switch', { name: 'Page appearance', exact: true })
  const control = toggle.locator('..')
  await expect(control.getByRole('button', { name: 'Theme preference', exact: true })).toHaveCount(0)
  await toggle.focus()
  await expect(toggle).toHaveCSS('outline-style', 'none')
  await expect(toggle.locator('[data-theme-toggle-part="track"]')).toHaveCSS('outline-width', '2px')
  await expect(toggle.locator('[data-theme-toggle-part="track"]')).toHaveCSS('outline-offset', '2px')
  const selected = await toggle.getAttribute('aria-checked')
  await page.keyboard.press('Space')
  await expect(toggle).toHaveAttribute('aria-checked', selected === 'true' ? 'false' : 'true')
  expect((await toggle.boundingBox())!.height).toBeGreaterThanOrEqual(44)
})

for (const variant of ['celestial', 'lcd']) test(`${variant} theme menu fits a narrow viewport and stays aligned in RTL`, async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 568 })
  await page.goto(`?theme${variant === 'lcd' ? '&lcd' : ''}`)
  const control = page.getByRole('switch', { name: 'Page appearance', exact: true }).locator('..')
  await control.evaluate((element) => { element.dir = 'rtl' })
  const preference = control.getByRole('button', { name: 'Theme preference', exact: true })
  await preference.click()
  const menu = control.getByRole('menu')
  const bounds = (await menu.boundingBox())!
  expect(bounds.x).toBeGreaterThanOrEqual(8)
  expect(bounds.x + bounds.width).toBeLessThanOrEqual(312)
  expect(bounds.y).toBeGreaterThanOrEqual(8)
  expect(bounds.y + bounds.height).toBeLessThanOrEqual(560)
  await page.keyboard.press('End')
  await expect(menu.getByRole('menuitemradio', { name: 'System', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(preference).toBeFocused()
})

test('the thumb actually travels through intermediate positions and redirects on another activation', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'light', reducedMotion: 'no-preference' })
  await page.goto('?theme&controlled&lcd')
  const toggle = page.getByRole('switch', { name: 'Page appearance', exact: true })
  const thumb = toggle.locator('[data-theme-toggle-part="selection"]')
  await toggle.focus()
  await page.keyboard.press('Space')
  const motion = await thumb.evaluate((element) => {
    const transition = element.getAnimations().find((animation) => animation instanceof CSSTransition && animation.transitionProperty === 'transform')
    if (!transition) return null
    transition.pause()
    transition.currentTime = 100
    return { x: new DOMMatrix(getComputedStyle(element).transform).m41, keyframes: transition.effect!.getKeyframes().map((frame) => frame.transform) }
  })
  expect(motion).not.toBeNull()
  expect(motion!.x).toBeGreaterThan(0)
  expect(motion!.x).toBeLessThan(40)
  expect(motion!.keyframes).toHaveLength(2)
  await page.keyboard.press('Space')
  await expect(toggle).toHaveAttribute('aria-checked', 'false')
  await expect(thumb).toHaveCSS('transform', 'matrix(1, 0, 0, 1, 0, 0)')
})

for (const variant of ['celestial', 'lcd']) test(`${variant} toggle follows the device until explicitly changed and respects reduced motion`, async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'light', reducedMotion: 'reduce' })
  await page.setViewportSize({ width: 320, height: 844 })
  await page.goto(`?theme${variant === 'lcd' ? '&lcd' : ''}`)
  const toggle = page.getByRole('switch', { name: 'Page appearance', exact: true })
  await expect(toggle).toHaveAttribute('aria-checked', 'false')
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(toggle).toHaveAttribute('aria-checked', 'true')
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-checked', 'false')
  await page.emulateMedia({ colorScheme: 'light' })
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(toggle).toHaveAttribute('aria-checked', 'false')
  await expect(toggle.locator('[data-theme-toggle-part="selection"]')).toHaveCSS('transition-duration', '0s')
  await expect(toggle.locator('[data-theme-toggle-part="sun"]')).toHaveCSS('opacity', '1')
  await expect(toggle.locator('[data-theme-toggle-part="moon"]')).toHaveCSS('opacity', '0')
  const rect = await toggle.boundingBox()
  expect(rect!.width).toBeGreaterThanOrEqual(44)
  expect(rect!.height).toBeGreaterThanOrEqual(44)
})
