import { expect, test } from '@playwright/test'

test('compact date fields open a scrollable celestial picker and return focus on dismissal', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 720 })
  await page.goto('./?popup&dateonly')
  const field = page.getByRole('button', { name: /Choose date/ })
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(field).toContainText('31 Jan 2028')
  await field.click()
  const dialog = page.getByRole('dialog', { name: 'Choose date', exact: true })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('listbox')).toHaveCount(3)
  const orbit = (await dialog.locator('.orrery-control-stage').boundingBox())!
  expect(orbit.width).toBeGreaterThan(350)
  expect(orbit.y + orbit.height).toBeLessThanOrEqual((await dialog.locator('.picker-dialog-footer').boundingBox())!.y)
  await expect(dialog.getByRole('slider', { name: 'Rotate Earth to set time' })).toHaveCount(0)
  await dialog.getByRole('listbox', { name: 'Month', exact: true }).press('ArrowDown')
  await expect(page.getByTestId('popup-date')).toHaveText('2028-02-29T15:59:00.000Z')
  await dialog.getByRole('listbox', { name: 'Year', exact: true }).press('ArrowDown')
  await expect(page.getByTestId('popup-date')).toHaveText('2029-02-28T15:59:00.000Z')
  await expect(dialog.getByRole('slider', { name: 'Year on Jupiter’s orbit' })).toBeVisible()
  await dialog.getByRole('listbox', { name: 'Day', exact: true }).press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(field).toBeFocused()
  await page.getByRole('button', { name: 'Set date from host' }).click()
  await expect(field).toContainText('1 Mar 2029')
  await field.click()
  await expect(dialog.getByRole('listbox', { name: 'Day', exact: true }).getByRole('option', { selected: true })).toHaveText('01')
  await dialog.getByRole('listbox', { name: 'Year', exact: true }).press('End')
  await expect(dialog.locator('.orbit-range-navigation')).toContainText('2400')
  await dialog.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(field).toBeFocused()
})

test('native mouse and trackpad scrolling selects a precise time with a coupled civil day', async ({ page }) => {
  await page.goto('./?popup')
  await page.getByRole('button', { name: /Choose time/ }).click()
  const dialog = page.getByRole('dialog', { name: 'Choose time', exact: true })
  const hours = dialog.getByRole('listbox', { name: 'Hours', exact: true })
  const minutes = dialog.getByRole('listbox', { name: 'Minutes', exact: true })
  await expect(minutes.getByRole('option', { selected: true })).toHaveText('59')
  await minutes.hover()
  await page.mouse.wheel(0, -44)
  await expect(page.getByTestId('popup-date')).toHaveText('2028-01-31T15:58:00.000Z')
  await hours.press('Home')
  await expect(page.getByTestId('popup-date')).toHaveText('2028-01-30T16:58:00.000Z')
  await dialog.getByRole('listbox', { name: 'Day', exact: true }).press('ArrowDown')
  await expect(page.getByTestId('popup-date')).toHaveText('2028-01-31T16:58:00.000Z')
  await expect(dialog.getByRole('spinbutton', { name: 'Hours', exact: true })).toHaveValue('00')
  await expect(dialog.getByRole('spinbutton', { name: 'Minutes', exact: true })).toHaveValue('58')
  await dialog.getByRole('button', { name: 'Increase minutes' }).click()
  await expect(page.getByTestId('popup-date')).toHaveText('2028-01-31T16:59:00.000Z')
  await expect(minutes.getByRole('option', { selected: true })).toHaveText('59')
  await dialog.getByRole('combobox', { name: 'Earth view', exact: true }).selectOption('city')
  await dialog.getByRole('combobox', { name: 'City in view', exact: true }).selectOption('Paris')
  await dialog.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(page.getByRole('button', { name: /Choose time/ })).toContainText('1 Feb 2028 · 00:59')
  await page.getByRole('button', { name: /Choose time/ }).click()
  await expect(dialog.getByRole('combobox', { name: 'Earth view', exact: true })).toHaveValue('city')
  await expect(dialog.locator('.earth-view-location')).toContainText('Paris')
})

test('popover fields keep keyboard focus contained, respect read-only dates and fit narrow screens without WebGL', async ({ page }) => {
  await page.addInitScript(() => {
    const original = HTMLCanvasElement.prototype.getContext
    HTMLCanvasElement.prototype.getContext = function (type: string, ...args: unknown[]) {
      if (type.includes('webgl')) return null
      return original.apply(this, [type, ...args] as Parameters<typeof original>)
    } as typeof original
  })
  await page.setViewportSize({ width: 320, height: 700 })
  await page.goto('./?popup&readonly')
  await page.getByRole('button', { name: /Choose date/ }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('listbox', { name: 'Hours', exact: true })).toHaveAttribute('aria-disabled', 'true')
  await expect(dialog.getByRole('button', { name: 'Done', exact: true })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  expect(await dialog.evaluate((element) => element.contains(document.activeElement))).toBe(true)
  const box = await dialog.boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(320)
  expect(await dialog.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
  await page.keyboard.press('Escape')
  await page.goto('./?popup&disabled')
  await expect(page.getByRole('button', { name: /Choose date/ })).toBeDisabled()
  await expect(page.getByRole('button', { name: /Choose time/ })).toBeDisabled()
})
