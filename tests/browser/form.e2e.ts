import { expect, test } from '@playwright/test'

test('a compact year field submits, clears, validates and resets with its host form', async ({ page }) => {
  await page.goto('./?form&year')
  const field = page.getByRole('button', { name: 'Starts', exact: true })
  await expect(field).toHaveCSS('height', '32px')
  await field.click()
  const panel = page.getByRole('dialog', { name: 'Starts', exact: true })
  await expect(panel.getByRole('listbox')).toHaveCount(1)
  await panel.getByRole('listbox', { name: 'Year', exact: true }).press('ArrowDown')
  await panel.getByRole('button', { name: 'Done' }).click()
  await expect(field).toBeFocused()
  await page.getByRole('button', { name: 'Submit', exact: true }).click()
  await expect(page.getByTestId('form-result')).toContainText('"startsAt":"2029"')
  await field.click()
  await panel.getByRole('button', { name: 'Clear', exact: true }).click()
  await panel.getByRole('button', { name: 'Done' }).click()
  await page.getByRole('button', { name: 'Submit', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveText('Choose a value.')
  await expect(field).toBeFocused()
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await expect(field).toContainText('2028')
  await expect(page.getByRole('alert')).toHaveCount(0)
  await page.goto('./?form&year&cancelreset')
  await field.click()
  await panel.getByRole('listbox', { name: 'Year', exact: true }).press('ArrowDown')
  await panel.getByRole('button', { name: 'Done' }).click()
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await expect(field).toContainText('2029')
})

test('form controls honor precision, controlled updates, civil steps and read-only or disabled values', async ({ page }) => {
  await page.goto('./?form&controlled&stepper')
  const field = page.getByRole('button', { name: 'Starts', exact: true })
  await field.click()
  const panel = page.getByRole('dialog', { name: 'Starts', exact: true })
  await panel.getByRole('button', { name: 'Increase minutes', exact: true }).click()
  await expect(panel.getByRole('spinbutton', { name: 'Minutes', exact: true })).toHaveValue('14')
  await expect(panel.getByRole('spinbutton', { name: 'Day', exact: true })).toHaveValue('01')
  await panel.press('Escape')
  await page.getByRole('button', { name: 'Set form value from host', exact: true }).click()
  await expect(field).toContainText('2029-02-28 · 12:30:00')
  const primitives = page.getByRole('region', { name: 'Reusable controls' })
  await primitives.getByRole('button', { name: 'Increase minutes' }).click()
  await expect(page.getByTestId('primitive-value')).toHaveText('2029-02-28T04:45:00.000Z')
  await page.goto('./?form&readonly')
  await field.click()
  await expect(panel.getByRole('listbox', { name: 'Year', exact: true })).toHaveAttribute('aria-disabled', 'true')
  await panel.press('Escape')
  await page.goto('./?form&disabled')
  await expect(field).toBeDisabled()
  await page.getByRole('button', { name: 'Submit', exact: true }).click()
  await expect(page.getByTestId('form-result')).not.toContainText('startsAt')
})

test('scrolling form popovers fit a narrow viewport, keep bounds and dismiss without taking focus from another field', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 700 })
  await page.goto('./?form')
  const field = page.getByRole('button', { name: 'Starts', exact: true })
  await field.click()
  const panel = page.getByRole('dialog', { name: 'Starts', exact: true })
  const box = (await panel.boundingBox())!
  expect(box.x).toBeGreaterThanOrEqual(0)
  expect(box.x + box.width).toBeLessThanOrEqual(320)
  expect(await panel.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
  const minutes = panel.getByRole('listbox', { name: 'Minutes', exact: true })
  await minutes.press('Home')
  await minutes.hover()
  await page.mouse.wheel(0, 36)
  await expect(minutes.getByRole('option', { selected: true })).toHaveText('15')
  const year = panel.getByRole('listbox', { name: 'Year', exact: true })
  await year.press('End')
  await year.press('ArrowDown')
  await expect(year.getByRole('option', { selected: true })).toHaveText('2029')
  await page.getByRole('textbox', { name: 'Title', exact: true }).click()
  await expect(panel).toHaveCount(0)
  await expect(page.getByRole('textbox', { name: 'Title', exact: true })).toBeFocused()
})
