import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

for (const lcd of [false, true]) {
  const style = lcd ? 'LCD' : '3D'
  const url = `./?scheduling${lcd ? '&lcd' : ''}`
  test(`${style}: one range window keeps endpoints explicit and submits/reset/clears`, async ({ page }) => {
    await page.goto(url)
    const field = page.getByRole('button', { name: 'Booking', exact: true })
    await field.click()
    const panel = page.getByRole('dialog', { name: 'Booking', exact: true })
    await expect(panel.getByRole('button', { name: 'Start', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await panel.getByRole('listbox', { name: 'Day', exact: true }).press('ArrowDown')
    await expect(panel).toBeVisible()
    await expect(panel.getByRole('button', { name: 'Start', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await panel.getByRole('button', { name: 'End', exact: true }).click()
    await panel.getByRole('listbox', { name: 'Day', exact: true }).press('ArrowDown')
    await expect(panel.locator('[data-picker-part="rangeTrack"]')).toHaveCount(1)
    await panel.getByRole('button', { name: 'Done', exact: true }).click()
    await expect(field).toBeFocused()
    await page.getByRole('button', { name: 'Submit', exact: true }).click()
    await expect(page.getByTestId('scheduling-result')).toContainText('"booking.start":"2026-11-10"')
    await expect(page.getByTestId('scheduling-result')).toContainText('"booking.end":"2026-11-11"')
    await page.getByRole('button', { name: 'Reset', exact: true }).click()
    await expect(page.locator('input[name="booking.start"]')).toHaveValue('2026-11-09')
    await field.click()
    await panel.getByRole('button', { name: 'Clear', exact: true }).click()
    await panel.getByRole('button', { name: 'Done', exact: true }).click()
    await page.getByRole('button', { name: 'Submit', exact: true }).click()
    await expect(page.getByRole('alert')).toBeVisible()
  })
  test(`${style}: unavailable dates/times are blocked and invalid host values cannot submit`, async ({ page }) => {
    await page.goto(url)
    const field = page.getByRole('button', { name: 'Appointment', exact: true })
    await field.click()
    const panel = page.getByRole('dialog', { name: 'Appointment', exact: true })
    const day = panel.getByRole('listbox', { name: 'Day', exact: true })
    await expect(day.getByRole('option', { name: '08', exact: true })).toHaveAttribute('aria-disabled', 'true')
    const hour = panel.getByRole('listbox', { name: 'Hours', exact: true })
    await expect(hour.getByRole('option', { name: '17', exact: true })).toHaveAttribute('aria-disabled', 'true')
    await day.getByRole('option', { name: '08', exact: true }).click({ force: true })
    await expect(page.getByTestId('appointment-value')).toHaveText('2026-11-09T10:00:00.000Z')
    await hour.press('End')
    await expect(page.getByTestId('appointment-value')).toHaveText('2026-11-09T16:00:00.000Z')
    await expect(panel.locator('[data-picker-part="unavailableTrack"]').first()).toBeAttached()
    await panel.getByRole('button', { name: 'Done', exact: true }).click()
    await page.getByRole('button', { name: 'Unavailable date from host' }).click()
    await expect(field).toHaveAttribute('aria-invalid', 'true')
    await page.getByRole('button', { name: 'Submit', exact: true }).click()
    await expect(page.getByRole('alert')).toHaveText('This date or time is unavailable.')
    await expect(page.getByTestId('scheduling-result')).toBeEmpty()
  })
  test(`${style}: localization, 12-hour selection and date-only values survive zone changes`, async ({ page }) => {
    await page.goto(`${url}&locale=fr-FR&h12`)
    await page.getByRole('button', { name: 'Appointment', exact: true }).click()
    const panel = page.getByRole('dialog', { name: 'Appointment', exact: true })
    await expect(panel.getByRole('listbox', { name: 'Année', exact: true })).toBeVisible()
    const order = await panel.locator('[data-picker-part="controlGroup"] > [data-unit]').evaluateAll((elements) => elements.map((element) => element.getAttribute('data-unit')))
    expect(order.slice(0, 3)).toEqual(['day', 'month', 'year'])
    await panel.getByRole('listbox', { name: 'Heures', exact: true }).press('End')
    await expect(page.getByTestId('appointment-value')).toHaveText('2026-11-09T16:00:00.000Z')
    await expect(panel.getByRole('button', { name: 'PM', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await panel.getByRole('button', { name: 'Minutes', exact: true }).click()
    await expect(panel).toBeVisible()
    await panel.getByRole('button', { name: 'Terminer', exact: true }).click()
    await page.getByRole('button', { name: 'Change time zone' }).click()
    await expect(page.getByTestId('birthday-value')).toHaveText('{"year":1990,"month":6,"day":15}')
    await expect(page.locator('input[name="birthday"]')).toHaveValue('1990-06-15')
  })
  test(`${style}: typed localized digits respect availability and year-only ranges omit Earth`, async ({ page }) => {
    await page.goto(`${url}&locale=ar-EG&stepper`)
    await page.getByRole('button', { name: 'Appointment', exact: true }).click()
    const panel = page.getByRole('dialog', { name: 'Appointment', exact: true })
    const minutes = panel.getByRole('spinbutton', { name: 'الدقائق', exact: true })
    await minutes.fill('٣٠')
    await minutes.press('Enter')
    await expect(page.getByTestId('appointment-value')).toHaveText('2026-11-09T10:30:00.000Z')
    const hours = panel.getByRole('spinbutton', { name: 'الساعات', exact: true })
    await hours.fill('١٨')
    await hours.press('Enter')
    await expect(page.getByTestId('appointment-value')).toHaveText('2026-11-09T10:30:00.000Z')
    await minutes.fill('٤٥')
    await minutes.press('Escape')
    await expect(page.getByTestId('appointment-value')).toHaveText('2026-11-09T10:30:00.000Z')
    await page.goto(`${url}&yearrange`)
    await page.getByRole('button', { name: 'Booking', exact: true }).click()
    const range = page.getByRole('dialog', { name: 'Booking', exact: true })
    await range.getByRole('button', { name: 'End', exact: true }).click()
    await range.getByRole('listbox', { name: 'Year', exact: true }).press('ArrowDown')
    await expect(range.getByRole('listbox')).toHaveCount(1)
    await expect(range.locator('.orbit-hit-day')).toHaveCount(0)
    await expect(range.locator('[data-picker-part="rangeTrack"]')).toHaveCount(1)
    await expect(range.locator('[data-picker-part="rangeEndpoint"]')).toHaveCount(2)
  })
  test(`${style}: RTL, enlarged text, forced colours and touch-sized controls remain accessible`, async ({ page }) => {
    await page.setViewportSize({ width: 320, height: 740 })
    await page.goto(`${url}&locale=ar-EG`)
    await page.addStyleTag({ content: 'html { font-size: 200%; }' })
    await page.getByRole('button', { name: 'Booking', exact: true }).click()
    const panel = page.getByRole('dialog', { name: 'Booking', exact: true })
    await expect(panel).toHaveCSS('direction', 'rtl')
    const bounds = (await panel.boundingBox())!
    expect(bounds.x).toBeGreaterThanOrEqual(0)
    expect(bounds.x + bounds.width).toBeLessThanOrEqual(320)
    expect(await panel.evaluate((el) => el.scrollWidth <= el.clientWidth + 1)).toBe(true)
    const scan = await new AxeBuilder({ page }).include('[popover]').withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()
    expect(scan.violations).toEqual([])
    await page.emulateMedia({ forcedColors: 'active', reducedMotion: 'reduce' })
    await panel.getByRole('button', { name: 'النهاية', exact: true }).click()
    await expect(panel).toBeVisible()
    await panel.press('Escape')
    await expect(page.getByRole('button', { name: 'Booking', exact: true })).toBeFocused()
  })
}

for (const low of [false, true]) test(`one isolated 3D planet shares only its own ${low ? 'compact' : 'detailed'} texture`, async ({ page }) => {
  const textures: string[] = []
  page.on('request', (request) => { if (/\.(jpg|png)(\?|$)/.test(request.url())) textures.push(request.url()) })
  await page.goto(`./?scheduling&planetperf${low ? '&low' : ''}`)
  await expect(page.locator('.planet-globe[data-ready="true"]')).toHaveCount(2)
  const chosenMap = low ? /jupiter_1k/ : /jupiter_2k/
  expect(textures.filter((url) => chosenMap.test(url))).toHaveLength(1)
  expect(textures.some((url) => !chosenMap.test(url))).toBe(false)
})
