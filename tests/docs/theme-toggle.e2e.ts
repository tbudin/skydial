import { expect, test } from '@playwright/test'
import { setDesignStyle, setPalette, setAppearance } from './preview.js'

test('3D Sun activity and night stars animate only when allowed and visible', async ({ page }) => {
  const shaderErrors: string[] = []
  page.on('console', (message) => { if (message.type() === 'error' && /shader|WebGLProgram/i.test(message.text())) shaderErrors.push(message.text()) })
  await page.clock.install()
  await page.goto('./widgets/#theme-toggle')
  await setAppearance(page, 'light')
  const control = page.getByRole('article', { name: '3D toggle example', exact: true }).locator('.celestial-theme-toggle')
  const toggle = control.getByRole('switch')
  const sun = control.locator('canvas[data-toggle-globe="sun"]')
  const moon = control.locator('canvas[data-toggle-globe="moon"]')
  await expect(sun).toHaveAttribute('data-ready', 'true')
  await expect(sun).toHaveAttribute('data-motion', 'solar')
  await page.clock.pauseAt(Date.now() + 1000)
  const before = Number(await sun.getAttribute('data-solar-seconds'))
  await page.clock.runFor(500)
  expect(Number(await sun.getAttribute('data-solar-seconds'))).toBeGreaterThan(before)
  await toggle.click()
  await expect(moon).toHaveAttribute('data-motion', 'turning')
  await page.clock.runFor(250)
  await expect(moon).toHaveAttribute('data-motion', 'idle')
  await expect(control.locator('.theme-toggle-stars i').first()).toHaveCSS('animation-play-state', 'running')
  const stopped = await sun.getAttribute('data-solar-seconds')
  await page.clock.runFor(500)
  expect(await sun.getAttribute('data-solar-seconds')).toBe(stopped)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(control).toHaveAttribute('data-scene-motion', 'paused')
  await toggle.click()
  await expect(sun).toHaveAttribute('data-motion', 'idle')
  await page.clock.runFor(500)
  expect(await sun.getAttribute('data-solar-seconds')).toBe(stopped)
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await expect(sun).toHaveAttribute('data-motion', 'solar')
  await page.getByRole('heading', { name: 'Parameters', exact: true }).scrollIntoViewIfNeeded()
  await expect(control).toHaveAttribute('data-scene-motion', 'paused')
  await expect(sun).toHaveAttribute('data-motion', 'idle')
  const offscreen = await sun.getAttribute('data-solar-seconds')
  await page.clock.runFor(500)
  expect(await sun.getAttribute('data-solar-seconds')).toBe(offscreen)
  expect(shaderErrors).toEqual([])
})

test('compact toggles change the actual page theme, show one active body and offer both LCD artworks', async ({ page }) => {
  await page.goto('./widgets/#theme-toggle')
  await setAppearance(page, 'Light')
  const section = page.locator('#theme-toggle')
  for (const name of ['3D toggle example', 'LCD symbols toggle example', 'LCD illustrated toggle example']) {
    const example = section.getByRole('article', { name, exact: true })
    const toggle = example.getByRole('switch', { name: 'Dark mode' })
    await toggle.click()
    await expect(toggle).toHaveAttribute('aria-checked', 'true')
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
    await expect(section.locator('[data-theme-toggle-part="status"]')).toHaveText(['Dark', 'Dark', 'Dark'])
    await toggle.click()
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
    await expect(section.locator('[data-theme-toggle-part="status"]')).toHaveText(['Light', 'Light', 'Light'])
  }
  await setDesignStyle(page, 'lcd')
  await expect(section.getByRole('article', { name: '3D toggle example', exact: true })).toHaveCount(0)
  await expect(section.locator('canvas')).toHaveCount(0)
  await setPalette(page, 'Amber')
  const lcd = section.getByRole('article', { name: 'LCD illustrated toggle example', exact: true })
  await expect(lcd.locator('[data-theme-toggle-part="track"]')).toHaveCSS('background-color', 'rgb(243, 223, 175)')
  await expect(lcd.locator('[data-theme-toggle-part="selection"]')).toHaveCSS('background-color', 'rgb(73, 49, 25)')
  await expect(lcd.locator('[data-toggle-illustration]')).toHaveCount(2)
  await expect(lcd.locator('canvas')).toHaveCount(0)
  await section.getByText('Toggle settings', { exact: true }).click()
  await section.getByRole('checkbox', { name: 'Right to left', exact: true }).check()
  for (const [size, width] of [['small', 52], ['medium', 64], ['large', 76]] as const) {
    await section.getByRole('button', { name: size, exact: true }).click()
    await expect(lcd.getByRole('switch')).toHaveAttribute('data-toggle-size', size)
    await expect(lcd.locator('[data-theme-toggle-part="track"]')).toHaveCSS('width', `${width}px`)
  }
  await page.setViewportSize({ width: 320, height: 844 })
  expect(await section.evaluate((element) => [...element.querySelectorAll('.theme-toggle-example')].every((example) => example.getBoundingClientRect().right <= innerWidth))).toBe(true)
  await section.getByRole('checkbox', { name: 'Show current theme', exact: true }).uncheck()
  await expect(section.locator('[data-theme-toggle-part="status"]')).toHaveCount(0)
  await section.getByRole('checkbox', { name: 'Disabled', exact: true }).check()
  await expect(lcd.getByRole('switch')).toBeDisabled()
})
