import { expect, test } from '@playwright/test'

for (const variant of ['celestial', 'lcd']) test(`${variant} scheduling page submits ranges and applies external component settings`, async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto(`./scheduling/?style=${variant}`)
  const field = page.getByRole('button', { name: 'Booking', exact: true })
  await field.click()
  const panel = page.getByRole('dialog', { name: 'Booking', exact: true })
  await panel.getByRole('button', { name: 'End', exact: true }).click()
  await panel.getByRole('listbox', { name: 'Day', exact: true }).press('PageDown')
  await panel.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(field).toBeFocused()
  await page.getByRole('button', { name: 'Submit example', exact: true }).click()
  const submitted = page.getByRole('status', { name: 'Submitted values', exact: true })
  await expect(submitted).toContainText('"booking.start": "2026-11-09"')
  await expect(submitted).toContainText('"booking.end": "2026-11-15"')
  await expect(submitted).toContainText('"birthday": "1990-06-15"')

  await page.getByRole('button', { name: 'Birthday (calendar date)', exact: true }).click()
  const birthday = page.getByRole('dialog', { name: 'Birthday (calendar date)', exact: true })
  await birthday.getByRole('listbox', { name: 'Month', exact: true }).press('ArrowDown')
  await birthday.getByRole('button', { name: 'Done', exact: true }).click()
  await page.getByRole('button', { name: 'Submit example', exact: true }).click()
  await expect(submitted).toContainText('"birthday": "1990-07-15"')
  await page.getByRole('button', { name: 'Reset example', exact: true }).click()
  await expect(page.locator('input[name="birthday"]')).toHaveValue('1990-06-15')
  await expect(page.locator('input[name="booking.end"]')).toHaveValue('2026-11-10')
  await page.getByRole('button', { name: 'Submit example', exact: true }).click()
  await expect(submitted).toContainText('"booking.end": "2026-11-10"')
  await expect(submitted).toContainText('"birthday": "1990-06-15"')

  await page.getByText('Component settings', { exact: true }).click()
  await page.getByRole('combobox', { name: 'Range units', exact: true }).selectOption('year')
  await page.getByRole('combobox', { name: 'Year planet', exact: true }).selectOption('saturn')
  await field.click()
  await expect(panel.getByRole('slider', { name: 'Year on Saturn’s orbit', exact: true })).toBeVisible()
  await expect(panel.getByRole('slider', { name: 'Day of year on the calendar ring', exact: true })).toHaveCount(0)
  await expect(panel.getByRole('listbox')).toHaveCount(1)
  await panel.getByRole('button', { name: 'Done', exact: true }).click()

  await page.getByRole('combobox', { name: 'Range units', exact: true }).selectOption('seconds')
  await field.click()
  const seconds = panel.getByRole('group', { name: 'Earth drag precision', exact: true }).getByRole('button', { name: 'Seconds', exact: true })
  await seconds.click()
  await expect(seconds).toHaveAttribute('aria-pressed', 'true')
  await expect(panel).toBeVisible()
})
