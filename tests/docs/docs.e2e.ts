import { expect, test } from '@playwright/test'
import { previewHeader } from './preview.js'

test('package-site pages mount live examples and keep nested assets working', async ({ page }) => {
  const errors: string[] = []
  const missing: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('response', (response) => { if (response.status() >= 400) missing.push(response.url()) })
  await page.goto('./')
  await expect(page.getByRole('heading', { name: 'A small universe. In your hands.', exact: true })).toBeVisible()
  await expect(page.getByRole('slider', { name: 'Rotate Earth to set time' })).toBeVisible()
  const earth = page.getByRole('region', { name: 'Earth time picker' })
  await earth.getByRole('button', { name: 'Minutes', exact: true }).click()
  await earth.getByRole('button', { name: 'Increase minutes' }).click()
  await expect(earth.getByRole('spinbutton', { name: 'Minutes', exact: true })).toHaveValue('01')
  await page.getByRole('combobox', { name: 'Year planet', exact: true }).selectOption('saturn')
  await expect(page.getByRole('radio', { name: /Saturn/ })).toHaveAttribute('aria-checked', 'true')
  await earth.getByRole('combobox', { name: 'Earth view', exact: true }).selectOption('city')
  await earth.getByRole('combobox', { name: 'City in view', exact: true }).selectOption('Paris')
  await expect(earth.locator('.earth-view-location')).toHaveText('Paris · 48.86° N, 2.35° E')
  await expect(earth.locator('.earth-city-reticle')).toBeVisible()
  await page.getByRole('region', { name: 'Earth time picker' }).screenshot({ path: 'screenshots/earth-precision-desktop.png', animations: 'disabled' })
  await page.goto('./widgets/')
  await expect(page.locator('[data-widget-example]')).toHaveCount(4)
  await expect(page.getByRole('group', { name: 'Show', exact: true })).toHaveCount(0)
  const earthExample = page.locator('[data-widget-example="earth"]')
  const moonExample = page.locator('[data-widget-example="moon"]')
  const yearExample = page.locator('[data-widget-example="year"]')
  const solarExample = page.locator('[data-widget-example="orrery"]')
  for (const example of [earthExample, moonExample, yearExample, solarExample]) {
    await expect(example.locator('.celestial-card')).toHaveCount(1)
    await expect(example.getByRole('button', { name: 'Small', exact: true })).toBeVisible()
    await expect(example.getByRole('button', { name: 'Medium', exact: true })).toBeVisible()
    await expect(example.getByRole('button', { name: 'Large', exact: true })).toBeVisible()
  }
  await yearExample.getByRole('combobox', { name: 'Year hand planet' }).selectOption('saturn')
  await expect(yearExample.locator('.widget-caption')).toHaveText('29.5-year orbit')
  await expect(yearExample.locator('pre')).toContainText('defaultPlanet="saturn"')
  await page.getByRole('combobox', { name: 'Observer city', exact: true }).selectOption('Singapore')
  await expect(earthExample.locator('.widget-value')).toHaveText('20:00')
  await page.getByLabel('Time (UTC)', { exact: true }).fill('13:15')
  await expect(earthExample.locator('.widget-value')).toHaveText('21:15')
  await expect(earthExample.locator('pre')).toContainText('Asia/Singapore')
  await expect(solarExample.locator('.label-layer')).toBeEmpty()
  await expect(solarExample.locator('canvas')).toBeVisible()
  await page.screenshot({ path: 'screenshots/docs-widgets-desktop.png', fullPage: true, animations: 'disabled' })
  for (const example of [earthExample, moonExample, yearExample, solarExample]) {
    for (const [size, height] of [['Small', 176], ['Medium', 176], ['Large', 368]] as const) {
      await example.getByRole('button', { name: size, exact: true }).click()
      await expect(example.locator('.celestial-card')).toHaveCSS('height', `${height}px`)
    }
  }
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await earthExample.screenshot({ path: 'screenshots/docs-widget-earth-mobile.png', animations: 'disabled' })
  await solarExample.screenshot({ path: 'screenshots/docs-widget-orrery-mobile.png', animations: 'disabled' })
  await page.setViewportSize({ width: 320, height: 844 })
  await earthExample.getByRole('button', { name: 'Medium', exact: true }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(missing).toEqual([])
  expect(errors).toEqual([])
})

test('a clean picker shows Earth and one configured year planet with synchronized scrolling and steps', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.setViewportSize({ width: 1280, height: 720 })
  await page.goto('./picker/')
  const settings = page.getByRole('region', { name: 'Configure your picker' })
  const example = page.getByRole('region', { name: 'Website form example' })
  const field = example.getByRole('button', { name: 'Starts', exact: true })
  await expect(field).toHaveCSS('height', '32px')
  await field.click()
  let panel = page.getByRole('dialog', { name: 'Starts', exact: true })
  await expect(panel.getByRole('listbox')).toHaveCount(3)
  await expect(panel.getByRole('radio')).toHaveCount(0)
  await expect(panel.locator('[data-visible-bodies]')).toHaveAttribute('data-visible-bodies', 'earth jupiter')
  await expect(panel.locator('canvas')).toHaveCount(1)
  await expect(panel).not.toContainText(/A MOMENT IN ORBIT|TIME ON EARTH|Click a month|One swipe|Drag|Starts/)
  await expect(panel.locator('.picker-form-panel-title, .celestial-input-reading, .picker-instruction')).toHaveCount(0)
  await panel.getByRole('listbox', { name: 'Year', exact: true }).press('ArrowDown')
  await panel.getByRole('button', { name: 'Increase day', exact: true }).click()
  await panel.getByRole('slider', { name: 'Day of year on the calendar ring', exact: true }).press('ArrowRight')
  await expect(example.locator('input[name="startsAt"]')).toHaveValue('2027-03-22')
  await expect(panel.getByRole('listbox', { name: 'Day', exact: true }).getByRole('option', { selected: true })).toHaveText('22')
  await panel.getByRole('listbox', { name: 'Day', exact: true }).focus()
  await page.screenshot({ path: 'screenshots/docs-clean-picker-light.png', animations: 'disabled' })
  await panel.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(field).toBeFocused()
  await expect(field).toContainText('2027-03-22')
  await example.getByRole('button', { name: 'Save event', exact: true }).click()
  await expect(example.locator('.picker-submit-result')).toContainText('"startsAt": "2027-03-22"')
  await previewHeader(page).getByRole('combobox', { name: 'Appearance', exact: true }).selectOption('dark')
  await settings.getByRole('combobox', { name: 'Year planet', exact: true }).selectOption('saturn')
  await field.click()
  panel = page.getByRole('dialog', { name: 'Starts', exact: true })
  await expect(panel).toHaveCSS('background-color', 'rgb(11, 17, 27)')
  await expect(panel.locator('[data-visible-bodies]')).toHaveAttribute('data-visible-bodies', 'earth saturn')
  await expect(panel.getByRole('radio')).toHaveCount(0)
  await page.screenshot({ path: 'screenshots/docs-clean-picker-dark.png', animations: 'disabled' })
  await panel.press('Escape')
  await page.setViewportSize({ width: 1280, height: 1000 })
  await page.getByRole('group', { name: 'Picker presets' }).getByRole('button', { name: 'Date & time', exact: true }).click()
  await field.click()
  panel = page.getByRole('dialog', { name: 'Starts', exact: true })
  await expect(panel.getByRole('listbox')).toHaveCount(5)
  await expect(panel.getByRole('slider', { name: 'Rotate Earth to set time', exact: true })).toBeVisible()
  await expect(panel.locator('canvas')).toHaveCount(2)
  await expect(panel.locator('.scale-label.date-pill')).toHaveAttribute('data-visible', 'true')
  await expect(panel.getByRole('listbox', { name: 'Minutes', exact: true })).toBeInViewport()
  await expect(panel.getByRole('slider', { name: 'Rotate Earth to set time', exact: true })).toBeInViewport()
  await page.screenshot({ path: 'screenshots/docs-orbital-datetime-dark.png', animations: 'disabled' })
  await panel.press('Escape')
  await page.getByRole('group', { name: 'Picker presets' }).getByRole('button', { name: 'Time', exact: true }).click()
  await field.click()
  panel = page.getByRole('dialog', { name: 'Starts', exact: true })
  await expect(panel.locator('canvas')).toHaveCount(1)
  await expect(panel.getByRole('slider', { name: 'Rotate Earth to set time', exact: true })).toBeVisible()
  await expect(panel).not.toContainText(/One swipe|Drag|TIME ON EARTH|Starts/)
  await expect(panel.getByRole('listbox')).toHaveCount(2)
  await panel.getByRole('button', { name: 'Done', exact: true }).click()
  await page.getByRole('group', { name: 'Picker presets' }).getByRole('button', { name: 'Date', exact: true }).click()
  await page.setViewportSize({ width: 320, height: 740 })
  await field.click()
  panel = page.getByRole('dialog', { name: 'Starts', exact: true })
  await panel.getByRole('button', { name: 'Increase day', exact: true }).scrollIntoViewIfNeeded()
  await expect(panel.getByRole('button', { name: 'Increase day', exact: true })).toBeInViewport()
  const box = (await panel.boundingBox())!
  expect(box.x).toBeGreaterThanOrEqual(0)
  expect(box.x + box.width).toBeLessThanOrEqual(320)
  const anchor = (await field.boundingBox())!
  if (!(await panel.getAttribute('data-placement'))?.startsWith('viewport')) expect(box.y + box.height <= anchor.y - 5 || box.y >= anchor.y + anchor.height + 5).toBe(true)
  expect(await panel.locator('[data-picker-part="content"]').evaluate((el) => el.scrollHeight - el.clientHeight)).toBeLessThanOrEqual(1)
  const done = (await panel.getByRole('button', { name: 'Done', exact: true }).boundingBox())!
  expect(done.y + done.height).toBeLessThanOrEqual(740)
  await page.screenshot({ path: 'screenshots/docs-clean-picker-mobile.png', animations: 'disabled' })
  expect(errors).toEqual([])
})

