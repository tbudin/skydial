test('the builder applies and exports styles for every named part and orbital appearance', async ({ page }) => {
  await page.goto('./picker/')
  const settings = page.getByRole('region', { name: 'Configure your picker' })
  const example = page.getByRole('region', { name: 'Website form example' })
  await settings.getByRole('textbox', { name: 'CSS properties', exact: true }).fill('{"borderRadius":18,"borderColor":"#8b5cf6"}')
  await settings.getByRole('textbox', { name: 'CSS class', exact: true }).fill('my-date-input')
  const field = example.getByRole('button', { name: 'Starts', exact: true })
  await expect(field).toHaveCSS('border-radius', '18px')
  await expect(field).toHaveClass(/my-date-input/)
  await settings.getByRole('combobox', { name: 'Element to style', exact: true }).selectOption('panel')
  await settings.getByRole('textbox', { name: 'CSS properties', exact: true }).fill('{"background":"#faf5ff","padding":12}')
  await settings.getByRole('textbox', { name: 'Orbit style', exact: true }).fill('{"palette":{"yearHand":"#7c3aed"},"handWidth":2}')
  await settings.getByRole('spinbutton', { name: 'Wheel row height', exact: true }).fill('48')
  await field.click()
  const panel = page.getByRole('dialog', { name: 'Starts', exact: true })
  await expect(panel).toHaveCSS('background-color', 'rgb(250, 245, 255)')
  await expect(panel.getByRole('listbox', { name: 'Day', exact: true })).toHaveCSS('height', '144px')
  await expect(panel.locator('[data-picker-part="yearLabel"]').first()).toHaveCSS('color', 'rgb(124, 58, 237)')
  await panel.getByRole('button', { name: 'Done', exact: true }).click()
  const code = page.getByRole('region', { name: 'Your component code' })
  await expect(code).toContainText('styles={')
  await expect(code).toContainText('classNames={')
  await expect(code).toContainText('orbitalStyle={')
  await expect(code).toContainText('wheelRowHeight={48}')
})
