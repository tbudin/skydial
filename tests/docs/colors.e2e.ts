import AxeBuilder from '@axe-core/playwright'
import { expect, test } from '@playwright/test'
import { closeColours, openColours, previewHeader, setDesignStyle, setPalette } from './preview.js'

test('custom LCD colours follow all controls, themes and form selection', async ({ page }) => {
  await page.goto('./picker/?style=lcd')
  const example = page.getByRole('region', { name: 'Website form example' })
  const field = example.getByRole('button', { name: 'Starts', exact: true })
  await setPalette(page, 'Ice blue')
  const colours = await openColours(page)
  await colours.getByLabel('LCD ink colour code', { exact: true }).fill('#102f38')
  await colours.getByLabel('LCD screen', { exact: true }).fill('#cdebe0')
  await closeColours(page)
  for (const theme of ['dark', 'light', 'auto']) {
    await previewHeader(page).getByRole('combobox', { name: 'Appearance', exact: true }).selectOption(theme)
    await field.click()
    const panel = page.getByRole('dialog')
    await expect(panel).toHaveCSS('background-color', 'rgb(205, 235, 224)')
    await expect(panel.locator('.lcd-orrery')).toHaveCSS('color', 'rgb(16, 47, 56)')
    await expect(panel.locator('.picker-wheel-selection').first()).toHaveCSS('background-color', 'rgb(16, 47, 56)')
    await panel.getByRole('listbox').first().press('ArrowDown')
    await panel.getByRole('button', { name: 'Done', exact: true }).click()
  }
  await expect(page.locator('.picker-primitives .celestial-control').first()).toHaveCSS('background-color', 'rgb(205, 235, 224)')
  await expect(page.getByRole('region', { name: 'Your component code' })).toContainText('colors={{"background":"#cdebe0","foreground":"#102f38"}}')
  await example.getByRole('button', { name: 'Save event', exact: true }).click()
  await expect(example.locator('output')).toContainText('2029-03-20')
  await page.emulateMedia({ colorScheme: 'dark' })
  const audit = await new AxeBuilder({ page }).include('.picker-builder').withTags(['wcag2aa', 'wcag21aa']).analyze()
  expect(audit.violations).toEqual([])
  await page.emulateMedia({ forcedColors: 'active' })
  await expect(field).toHaveCSS('background-color', await page.evaluate(() => { const el = document.createElement('span'); el.style.color = 'Canvas'; document.body.append(el); const color = getComputedStyle(el).color; el.remove(); return color }))
  await page.emulateMedia({ forcedColors: 'none' })
  await (await openColours(page)).getByRole('button', { name: 'Use theme colours', exact: true }).click()
  await closeColours(page)
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(field).toHaveCSS('background-color', 'rgb(26, 40, 31)')
  await page.emulateMedia({ colorScheme: 'light' })
  await expect(field).toHaveCSS('background-color', 'rgb(201, 207, 180)')
})

test('celestial colours reach the input and orbital labels without JSON editing', async ({ page }) => {
  await page.goto('./picker/')
  const colours = await openColours(page)
  await colours.getByLabel('Background', { exact: true }).fill('#fff8ef')
  await colours.getByLabel('Text', { exact: true }).fill('#342719')
  await colours.getByLabel('Accent', { exact: true }).fill('#684322')
  await colours.getByText('Orbit colours', { exact: true }).click()
  await colours.getByLabel('Year hand', { exact: true }).fill('#905e22')
  await closeColours(page)
  await page.getByRole('region', { name: 'Website form example' }).getByRole('button', { name: 'Starts', exact: true }).click()
  const panel = page.getByRole('dialog')
  await expect(panel).toHaveCSS('background-color', 'rgb(255, 248, 239)')
  await expect(panel).toHaveCSS('color', 'rgb(52, 39, 25)')
  await expect(panel.getByRole('option', { selected: true }).first()).toHaveCSS('color', 'rgb(104, 67, 34)')
  await expect(panel.locator('.scale-label.year-pill')).toHaveCSS('background-color', 'rgb(144, 94, 34)')
  await panel.getByRole('button', { name: 'Done', exact: true }).click()
  await setDesignStyle(page, 'lcd')
  await expect(previewHeader(page).getByRole('combobox', { name: 'Colour palette', exact: true, includeHidden: true })).toHaveValue('Theme defaults')
  await setDesignStyle(page, 'celestial')
  await expect((await openColours(page)).getByLabel('Background', { exact: true })).toHaveValue('#fff8ef')
})

test('widget colours and copied options update together and fit narrow screens', async ({ page }) => {
  await page.goto('./widgets/?style=lcd')
  await setPalette(page, 'Amber')
  for (const kind of ['earth', 'moon', 'year', 'orrery']) {
    const section = page.locator(`[data-widget-example="${kind}"]`)
    await expect(section.locator('.celestial-card')).toHaveCSS('background-color', 'rgb(243, 223, 175)')
    await expect(section.locator('.widget-value')).toHaveCSS('color', 'rgb(73, 49, 25)')
    await expect(section.locator('pre')).toContainText('colors={{"background":"#f3dfaf","foreground":"#493119"}}')
  }
  await setDesignStyle(page, 'celestial')
  const colours = await openColours(page)
  await colours.getByLabel('Background', { exact: true }).fill('#fff8ef')
  await colours.getByLabel('Text', { exact: true }).fill('#342719')
  await closeColours(page)
  for (const theme of ['light', 'dark']) {
    await page.getByRole('combobox', { name: 'Appearance', exact: true }).selectOption(theme)
    await expect(page.locator('[data-gallery-host="year"] .celestial-card')).toHaveCSS('background-color', 'rgb(255, 248, 239)')
    await expect(page.locator('[data-gallery-host="year"] .widget-value')).toHaveCSS('color', 'rgb(52, 39, 25)')
  }
  await setDesignStyle(page, 'lcd')
  await expect(page.getByRole('combobox', { name: 'Colour palette', exact: true, includeHidden: true })).toHaveValue('Amber')
  await page.setViewportSize({ width: 320, height: 740 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await (await openColours(page)).getByRole('button', { name: 'Use theme colours', exact: true }).click()
  await expect(page.locator('[data-widget-example="earth"] pre')).not.toContainText('colors=')
})
