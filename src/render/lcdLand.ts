function polygonContains(lon: number, lat: number, polygon: readonly (readonly number[])[]) {
  let hit = false
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const [xi, yi] = polygon[i]; const [xj, yj] = polygon[j]
    if ((yi > lat) !== (yj > lat) && lon < (xj - xi) * (lat - yi) / (yj - yi) + xi) hit = !hit
  }
  return hit
}
const shapes = LCD_LAND.map((points) => ({ points, minX: Math.min(...points.map((p) => p[0])), maxX: Math.max(...points.map((p) => p[0])), minY: Math.min(...points.map((p) => p[1])), maxY: Math.max(...points.map((p) => p[1])) }))
export function lcdLandAt(lon: number, lat: number) {
  return shapes.some((shape) => lon >= shape.minX && lon <= shape.maxX && lat >= shape.minY && lat <= shape.maxY && polygonContains(lon, lat, shape.points)) && !lakes.some((shape) => polygonContains(lon, lat, shape))
}
